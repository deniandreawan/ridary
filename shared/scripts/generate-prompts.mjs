#!/usr/bin/env node
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "../..");
const promptsDir = join(root, "shared", "prompts");
const swiftOut = join(root, "ios", "Ridary", "Generated", "Prompts.swift");
const tsOut = join(root, "web", "src", "generated", "prompts.ts");

const files = readdirSync(promptsDir)
  .filter((name) => name.endsWith(".md"))
  .sort();

if (files.length === 0) {
  throw new Error("No prompt markdown files found in shared/prompts");
}

const toCamel = (name) =>
  name
    .replace(/\.md$/, "")
    .split(/[-_]/)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)
    )
    .join("");

const toSnake = (name) => name.replace(/\.md$/, "");

const entries = files.map((file) => {
  const raw = readFileSync(join(promptsDir, file), "utf8").trim();
  return {
    file,
    key: toCamel(file),
    snake: toSnake(file),
    raw,
  };
});

const swiftEscape = (value) =>
  value.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');

const swiftLines = entries
  .map(
    (entry) =>
      `    /// Source: shared/prompts/${entry.file}\n` +
      `    static let ${entry.key} = """\n${swiftEscape(entry.raw)}\n"""\n`
  )
  .join("\n");

const swift = `// Generated by shared/scripts/generate-prompts.mjs. Do not edit by hand.
import Foundation

enum PromptTemplates {
${swiftLines}}

enum PromptKey: String, CaseIterable {
${entries.map((entry) => `    case ${entry.key} = "${entry.snake}"`).join("\n")}
}
`;

const tsEscape = (value) =>
  value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const tsEntries = entries
  .map(
    (entry) =>
      `  // Source: shared/prompts/${entry.file}\n` +
      `  ${entry.key}: \`${tsEscape(entry.raw)}\`,`
  )
  .join("\n\n");

const ts = `// Generated by shared/scripts/generate-prompts.mjs. Do not edit by hand.
export const promptTemplates = {
${tsEntries}
} as const;

export type PromptKey = keyof typeof promptTemplates;
`;

mkdirSync(dirname(swiftOut), { recursive: true });
mkdirSync(dirname(tsOut), { recursive: true });
writeFileSync(swiftOut, swift, "utf8");
writeFileSync(tsOut, ts, "utf8");

console.log(`Generated ${entries.length} prompts:`);
console.log(`  ${swiftOut}`);
console.log(`  ${tsOut}`);
